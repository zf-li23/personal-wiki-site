"""Spike trains of an inhomogeneous Poisson neuron and three estimates of its firing rate.

The true rate r(t) is a baseline of 5 Hz plus a fast transient (peak 80 Hz at 0.2 s) and a slow
sustained response (40 Hz between 0.5 s and 1.2 s). Spikes are generated by thinning: draw candidate
spikes at r_max and keep each with probability r(t)/r_max. Panel A: raster of 40 trials.
Panel B: PSTH with 25 ms bins. Panel C: Gaussian-kernel estimates with three widths.
"""
import matplotlib.pyplot as plt
import numpy as np

import wikibio as bio

P = bio.P
rng = np.random.default_rng(1)
T, dt = 1.6, 1e-3
t = np.arange(0, T, dt)


def rate(t):
    fast = 75 * np.exp(-0.5 * ((t - 0.2) / 0.025) ** 2)
    slow = 40 / (1 + np.exp(-(t - 0.5) / 0.02)) * (1 - 1 / (1 + np.exp(-(t - 1.2) / 0.03)))
    return 5 + fast + slow


r_true = rate(t)
r_max = r_true.max()
trials = []
for k in range(40):
    n = rng.poisson(r_max * T)
    cand = np.sort(rng.uniform(0, T, n))
    keep = rng.uniform(0, 1, n) < rate(cand) / r_max
    trials.append(cand[keep])

c_ink, c_true = P.ink(), P.muted()
cols = [P.edge("dna"), P.edge("rna"), P.edge("positive")]
fig, axs = plt.subplots(3, 1, figsize=(8.5, 7.2), sharex=True,
                        gridspec_kw={"height_ratios": [1.3, 1, 1]})
ax = axs[0]
for k, sp in enumerate(trials):
    ax.vlines(sp, k + 0.6, k + 1.4, color=c_ink, lw=0.7)
ax.set_ylabel("Trial")
ax.set_ylim(0.4, 40.6)
ax.set_title("A  Raster: 40 trials of the same stimulus", loc="left", fontsize=10)

allsp = np.concatenate(trials)
bins = np.arange(0, T + 1e-9, 0.025)
cnt, _ = np.histogram(allsp, bins)
bx = axs[1]
bx.bar(bins[:-1], cnt / (40 * 0.025), width=0.025, align="edge", color=P.fill("dna"),
       edgecolor=P.edge("dna"), lw=0.5, label="PSTH (25 ms bins)")
bx.plot(t, r_true, color=c_true, lw=1.4, ls="--", label="true rate r(t)")
bx.set_ylabel("Rate / Hz")
bx.legend(frameon=False, fontsize=8, loc="upper right")
bx.set_title("B  Peri-stimulus time histogram", loc="left", fontsize=10)

cx = axs[2]
cx.plot(t, r_true, color=c_true, lw=1.4, ls="--", label="true rate")
for sig, c in zip((0.005, 0.02, 0.08), cols):
    tk = np.arange(-4 * sig, 4 * sig + dt, dt)
    w = np.exp(-0.5 * (tk / sig) ** 2)
    w /= w.sum() * dt
    rho = np.zeros_like(t)
    idx = np.minimum((allsp / dt).astype(int), len(t) - 1)
    np.add.at(rho, idx, 1 / dt)
    est = np.convolve(rho, w, mode="same") * dt / 40
    cx.plot(t, est, color=c, lw=1.3, label=f"Gaussian kernel, sigma = {sig * 1000:.0f} ms")
cx.set_xlabel("Time after stimulus onset / s")
cx.set_ylabel("Rate / Hz")
cx.legend(frameon=False, fontsize=8, loc="upper right")
cx.set_title("C  Kernel estimates: variance versus temporal resolution", loc="left", fontsize=10)
fig.tight_layout()
