"""Mutualism with saturating benefits: dN_i/dt = N_i (r_i - c_i N_i + beta_i N_j / (h_j + N_j)).

All panels: c_i = 1, h_j = 1, symmetric parameters.
A: facultative mutualists, r = 1, beta = 1.5: the isoclines bend over and cross once; the equilibrium
N* = 2 for both species is globally stable for all positive initial densities.
B: obligate mutualists, r = -0.3 (each declines alone), beta = 3: the isoclines cross twice; the lower
crossing (N = 0.2) is a saddle whose stable manifold (dashed) is a threshold, the upper one (N = 1.5) is
stable, and the origin is stable too: an Allee effect generated by the partner.
C: symmetric equilibria N* against the maximal benefit beta. Facultative (r = 0.3): a single stable branch.
Obligate (r = -0.3): a stable branch (solid) and a threshold branch (dashed) that meet at the saddle-node
beta_c = h - r + 2 sqrt(-r h) = 2.40; below beta_c only extinction is possible.
"""

import numpy as np
from scipy.integrate import solve_ivp

import wikibio as bio
from wikibio import charts as C
from wikibio import quant as Q

P = bio.P
FS = bio.core.FONT
fig, ax = bio.canvas(33.0, 11.5)
xc, yc = Q.line_color("dna"), Q.line_color("negative")


def field(r, beta, h=1.0):
    def f(t, z):
        x, y = z
        return [x * (r - x + beta * y / (h + y)), y * (r - y + beta * x / (h + x))]
    return f


for i, (r, beta, lim, letter, title) in enumerate([(1.0, 1.5, 3.0, "A", "Facultative, saturating benefit"),
                                                   (-0.3, 3.0, 2.5, "B", "Obligate, saturating benefit")]):
    x0 = 2.0 + 11.0 * i
    pa = C.axes_at(ax, (x0, 1.7, 8.2, 8.2))
    g = np.linspace(0.001, lim, 23)
    X, Y = np.meshgrid(g, g)
    U = X * (r - X + beta * Y / (1 + Y))
    V = Y * (r - Y + beta * X / (1 + X))
    sp = np.hypot(U, V) + 1e-9
    pa.quiver(X, Y, U / sp, V / sp, color=P.mix(P.muted(), P.surface(), 0.35), scale=40, width=0.0035,
              headwidth=3.5, headlength=4)
    yy = np.linspace(0, lim, 300)
    iso1 = r + beta * yy / (1 + yy)
    m = iso1 >= 0
    pa.plot(iso1[m], yy[m], color=xc, lw=1.6, label="species 1 isocline")
    pa.plot(yy[m], iso1[m], color=yc, lw=1.6, label="species 2 isocline")
    f = field(r, beta)
    if r > 0:
        starts = [(0.05, 2.8), (2.8, 0.05), (0.05, 0.05), (2.9, 2.9), (1.5, 0.05), (0.05, 1.2)]
        ne = 0.5 * ((beta + r - 1) + np.sqrt((beta + r - 1) ** 2 + 4 * r))
        pa.plot([ne], [ne], "o", ms=6, color=P.ink())
    else:
        lo, hi = 0.2, 1.5
        J = np.array([[-lo, beta * lo / (1 + lo) ** 2], [beta * lo / (1 + lo) ** 2, -lo]])
        w, vec = np.linalg.eig(J)
        vs = vec[:, np.argmin(w)]
        for sgn in (1, -1):
            sol = solve_ivp(lambda t, z: [-c for c in f(t, z)], (0, 40), [lo + sgn * 1e-4 * vs[0], lo + sgn * 1e-4 * vs[1]],
                            max_step=0.02, events=lambda t, z: min(z) - 1e-3)
            pa.plot(sol.y[0], sol.y[1], color=P.ink(), lw=1.2, ls=(0, (4, 2)))
        pa.plot([hi], [hi], "o", ms=6, color=P.ink())
        pa.plot([lo], [lo], "o", ms=6, mfc=P.surface(), mec=P.ink(), mew=1.2)
        pa.plot([0], [0], "o", ms=6, color=P.ink(), clip_on=False)
        starts = [(0.3, 0.1), (0.1, 0.5), (0.6, 0.15), (0.4, 0.4), (2.4, 0.3), (0.3, 2.4), (2.3, 2.3), (1.0, 0.25)]
    for z0 in starts:
        sol = solve_ivp(f, (0, 40), z0, max_step=0.02, rtol=1e-8)
        pa.plot(sol.y[0], sol.y[1], color=P.ink(), lw=1.0)
        k = min(len(sol.t) - 2, 30)
        pa.annotate("", xy=(sol.y[0][k + 1], sol.y[1][k + 1]), xytext=(sol.y[0][k], sol.y[1][k]),
                    arrowprops=dict(arrowstyle="-|>", color=P.ink(), lw=0.9))
    pa.set_xlim(0, lim)
    pa.set_ylim(0, lim)
    C.style_axes(pa, "species 1, N1", "species 2, N2")
    pa.legend(frameon=False, fontsize=FS["tiny"], labelcolor=P.ink(), loc="upper left")
    bio.panel(ax, letter, (x0 - 1.7, 11.3))
    bio.label(ax, (x0, 10.6), title, size="small", bold=True, ha="left")

pc = C.axes_at(ax, (24.0, 1.7, 8.2, 8.2))
bet = np.linspace(0, 5, 600)
h = 1.0
for r, tok, name in [(0.3, "positive", "facultative, r = 0.3"), (-0.3, "rna", "obligate, r = -0.3")]:
    bq = h - r - bet
    disc = bq ** 2 + 4 * r * h
    ok = disc >= 0
    up = np.where(ok, (-bq + np.sqrt(np.where(ok, disc, 0))) / 2, np.nan)
    lo = np.where(ok, (-bq - np.sqrt(np.where(ok, disc, 0))) / 2, np.nan)
    pc.plot(bet, np.where(up > 0, up, np.nan), color=Q.line_color(tok), lw=1.8, label=name)
    if r < 0:
        pc.plot(bet, np.where(lo > 0, lo, np.nan), color=Q.line_color(tok), lw=1.4, ls=(0, (4, 2)))
        bc = h - r + 2 * np.sqrt(-r * h)
        pc.axvline(bc, color=P.muted(), lw=0.8, ls=":")
        pc.text(bc + 0.08, 3.6, "saddle-node\nbeta_c = 2.40", fontsize=FS["tiny"], color=P.ink())
pc.plot(bet, np.zeros_like(bet), color=P.ink(), lw=1.0)
pc.set_xlim(0, 5)
pc.set_ylim(-0.05, 4.2)
C.style_axes(pc, "maximal benefit, beta", "equilibrium density, N*")
pc.legend(frameon=False, fontsize=FS["tiny"], labelcolor=P.ink(), loc="upper left")
bio.panel(ax, "C", (22.3, 11.3))
bio.label(ax, (24.0, 10.6), "Equilibria and the benefit threshold", size="small", bold=True, ha="left")
