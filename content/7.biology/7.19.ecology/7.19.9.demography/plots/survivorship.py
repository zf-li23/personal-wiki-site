"""Survivorship curves (Section 9.3).

A, B: the three idealized types generated by a Weibull hazard mu(x) = (beta/eta) (x/eta)^(beta - 1),
with age scaled to the maximum life span (x in [0, 1]); beta > 1 type I, beta = 1 type II, beta < 1 type III.
The scale eta is chosen so that l(1) = 10^-3 in every case: l(x) = exp(-(x/eta)^beta).
C: two cohort life tables (data as tabulated by Begon & Townsend 2021): female yellow-bellied marmots,
Marmota flaviventris (Schwartz et al. 1998), and the barnacle Balanus glandula from settlement (Connell 1970).
"""

import matplotlib.pyplot as plt
import numpy as np

import wikibio as bio
from wikibio import charts as C

P = bio.P
FS = bio.core.FONT

fig, axes = plt.subplots(1, 3, figsize=(12.0, 3.9))
x = np.linspace(0.001, 1, 400)
lend = np.log(1e3)
types = [("Type I", 6.0, C.line("dna")), ("Type II", 1.0, C.line("positive")), ("Type III", 0.25, C.line("rna"))]

ax = axes[0]
for name, beta, col in types:
    eta = lend ** (-1 / beta)
    l = np.exp(-((x / eta) ** beta))
    ax.plot(x, np.log10(l), color=col, lw=2, label=f"{name} (β = {beta:g})")
ax.set_ylim(-3.2, 0.15)
ax.set_xlim(0, 1)
C.style_axes(ax, "age / maximum life span", "log₁₀ lₓ")
ax.legend(frameon=False, fontsize=FS["tiny"], labelcolor=P.ink(), loc="lower left")
C.title(ax, "A  Survivorship")

ax = axes[1]
for name, beta, col in types:
    eta = lend ** (-1 / beta)
    mu = beta / eta * (x / eta) ** (beta - 1)
    ax.plot(x, mu, color=col, lw=2, label=name)
ax.set_yscale("log")
ax.set_xlim(0, 1)
ax.set_ylim(0.05, 300)
C.style_axes(ax, "age / maximum life span", "hazard μ(x) (per life span)")
C.title(ax, "B  Age-specific risk of death")

ax = axes[2]
marmot = np.array([773, 420, 208, 139, 106, 67, 44, 31, 22, 12, 7, 3, 2, 2, 2, 1.0])
ax.plot(np.arange(16), np.log10(marmot / marmot[0]), "o-", ms=3.5, lw=1.5, color=C.line("animal"),
        label="marmot, females (years)")
barn = np.array([1e6, 62, 34, 20, 15.5, 11, 6.5, 2, 2])
ax.plot(np.arange(9), np.log10(barn / barn[0]), "s-", ms=3.5, lw=1.5, color=C.line("dna"),
        label="barnacle, from settling larvae (years)")
ax.annotate("larval and settlement\nmortality: k₀ = 4.2", (0.5, -2.1), (2.0, -3.6), fontsize=FS["tiny"],
            color=P.muted(), arrowprops=dict(arrowstyle="-", color=P.muted(), lw=0.7))
ax.set_xlim(-0.5, 15.5)
ax.set_ylim(-6.0, 0.3)
C.style_axes(ax, "age x", "log₁₀ lₓ")
ax.legend(frameon=False, fontsize=FS["tiny"], labelcolor=P.ink(), loc="upper right")
C.title(ax, "C  Two cohort life tables")

fig.tight_layout()
